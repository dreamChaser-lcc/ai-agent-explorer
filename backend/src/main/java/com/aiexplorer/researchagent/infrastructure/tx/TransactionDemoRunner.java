package com.aiexplorer.researchagent.infrastructure.tx;

import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * SP4 教学演示：启动后自动跑两组传播行为对比，并打印最终行数。可随时删除。
 *
 * 预期结果（详见讲义 §二）：
 *   场景 A（内层 REQUIRED）  → 0 行（整体回滚，提交时抛 UnexpectedRollbackException）
 *   场景 B（内层 REQUIRES_NEW）→ 2 行（outer-new, after-new）
 */
@Component
public class TransactionDemoRunner implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(TransactionDemoRunner.class);

    private final JdbcTemplate jdbcTemplate;
    private final TransactionDemoService transactionDemoService;

    public TransactionDemoRunner(JdbcTemplate jdbcTemplate, TransactionDemoService transactionDemoService) {
        this.jdbcTemplate = jdbcTemplate;
        this.transactionDemoService = transactionDemoService;
    }

    @Override
    public void run(ApplicationArguments args) {
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS sp4_tx_demo (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    label VARCHAR(64) NOT NULL
                )
                """);

        runScenarioA();
        runScenarioB();
    }

    /** 场景 A：内外层都 REQUIRED。 */
    private void runScenarioA() {
        jdbcTemplate.update("DELETE FROM sp4_tx_demo");
        try {
            transactionDemoService.outerRequired();
        } catch (Exception exception) {
            log.warn("[SP4-A] 外层方法在提交阶段抛出异常：{} - {}",
                    exception.getClass().getSimpleName(), exception.getMessage());
        }
        Integer rowCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM sp4_tx_demo", Integer.class);
        List<String> labels = jdbcTemplate.queryForList("SELECT label FROM sp4_tx_demo ORDER BY id", String.class);
        log.info("[SP4-A] 内层 REQUIRED：最终行数 = {}（预期 0），内容 = {}", rowCount, labels);
    }

    /** 场景 B：内层 REQUIRES_NEW。 */
    private void runScenarioB() {
        jdbcTemplate.update("DELETE FROM sp4_tx_demo");
        try {
            transactionDemoService.outerRequiresNew();
        } catch (Exception exception) {
            log.warn("[SP4-B] 外层方法抛出异常：{} - {}",
                    exception.getClass().getSimpleName(), exception.getMessage());
        }
        Integer rowCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM sp4_tx_demo", Integer.class);
        List<String> labels = jdbcTemplate.queryForList("SELECT label FROM sp4_tx_demo ORDER BY id", String.class);
        log.info("[SP4-B] 内层 REQUIRES_NEW：最终行数 = {}（预期 2），内容 = {}", rowCount, labels);
    }
}